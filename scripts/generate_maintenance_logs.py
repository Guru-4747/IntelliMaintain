"""Generate a labelled SYNTHETIC maintenance-log document for the knowledge base.

Real plants keep work-order histories ("maintenance logs"). They are confidential,
so - as stated in the project plan - we create a labelled synthetic log set whose
entries follow realistic patterns. Every entry is clearly marked synthetic.
Deterministic (fixed seed) so the knowledge base is reproducible.

Usage: python scripts/generate_maintenance_logs.py
"""
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from intellimaintain import config  # noqa: E402

ASSETS = ["Pump P-101", "Pump P-204", "Fan F-12", "Motor M-7", "Compressor C-3", "Conveyor drive CV-5"]
TEMPLATES = {
    "Outer race": [
        "Route measurement showed kurtosis {k} and envelope peaks at BPFO with 2 harmonics. Load-zone outer race defect "
        "suspected. Relubricated and increased monitoring to weekly. Bearing replaced at planned stop after {d} days; "
        "spall found on outer ring at 6 o'clock. Root cause: contamination dents from failed seal.",
        "Kurtosis {k}, RMS up 40 % from baseline. Clean BPFO harmonics without shaft sidebands. Replaced drive-end "
        "bearing during weekend shutdown. Outer race surface-initiated fatigue (ISO 15243). Seal upgraded.",
    ],
    "Inner race": [
        "Envelope spectrum showed BPFI with 1x rpm sidebands, kurtosis {k}. Shaft fit checked: interference too high. "
        "Bearing replaced within {d} days; inner ring spall found. New bearing mounted with induction heater.",
        "High-frequency energy and kurtosis {k} rising over 3 readings. BPFI and harmonics confirmed. Temperature rose "
        "6 C. Machine stopped early because inner race faults progress quickly. Inner ring cracked; misalignment corrected.",
    ],
    "Ball": [
        "Kurtosis {k} and crest factor elevated, envelope spectrum inconclusive (weak 2xBSF). Trended for {d} days; "
        "BPFO appeared later. Bearing replaced; one ball pitted, outer race indentations. Lubricant contained sand.",
        "Classifier flagged rolling-element fault, no clear defect lines in envelope. Analyst requested repeat "
        "measurements. Grease sample showed iron particles. Bearing replaced; two balls with surface damage.",
    ],
    "Normal": [
        "Routine measurement. RMS at baseline, kurtosis {k} (Gaussian-like), no defect frequencies in envelope spectrum. "
        "No action required; next measurement in 30 days.",
        "Post-replacement baseline recorded after run-in. Kurtosis {k}, no impacting. Alignment verified with laser tool.",
    ],
    "Lubrication": [
        "High-frequency noise floor elevated, kurtosis {k}. No discrete defect frequencies. Relubricated with specified "
        "grease; noise floor dropped by 60 % and stayed low. Diagnosis: lubrication deficiency, no bearing damage.",
    ],
    "Misalignment": [
        "High 1x and 2x running speed, high axial vibration, kurtosis {k}. No bearing defect frequencies. Laser "
        "alignment corrected; vibration back to zone A. Bearing not replaced.",
    ],
}
KURT = {"Outer race": (5.5, 12.0), "Inner race": (5.0, 10.0), "Ball": (4.0, 7.0), "Normal": (2.8, 3.3),
        "Lubrication": (3.3, 4.2), "Misalignment": (2.5, 3.2)}


def main(n_per_page: int = 6, seed: int = 7) -> Path:
    rng = random.Random(seed)
    entries = []
    wo = 4100
    for label, temps in TEMPLATES.items():
        reps = 5 if label in ("Outer race", "Inner race", "Ball", "Normal") else 3
        for i in range(reps):
            t = temps[i % len(temps)]
            k = round(rng.uniform(*KURT[label]), 1)
            wo += rng.randint(3, 40)
            entries.append((label, f"WO-{wo} | {rng.choice(ASSETS)} | 2025-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d} "
                                   f"| Label: {label} | " + t.format(k=k, d=rng.randint(5, 40))))
    rng.shuffle(entries)
    lines = ["---", "title: Synthetic Maintenance Work-Order Log (labelled)",
             "type: SYNTHETIC maintenance log generated by scripts/generate_maintenance_logs.py - not real plant data", "---", ""]
    for p in range(0, len(entries), n_per_page):
        lines.append(f"# Log page {p // n_per_page + 1}")
        lines.append("")
        for _, text in entries[p:p + n_per_page]:
            lines.append(f"- {text}")
            lines.append("")
    out = config.CORPUS_DIR / "kb09_synthetic_maintenance_logs.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(entries)} synthetic log entries -> {out}")
    return out


if __name__ == "__main__":
    main()
